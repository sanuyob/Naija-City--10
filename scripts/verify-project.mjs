import { readFile } from 'node:fs/promises';
import assert from 'node:assert/strict';
const html=await readFile(new URL('../index.html',import.meta.url),'utf8');
const entry=await readFile(new URL('../src/main.js',import.meta.url),'utf8');
const game=await readFile(new URL('../src/game.js',import.meta.url),'utf8');
const assets=await readFile(new URL('../src/scene-assets.js',import.meta.url),'utf8');
const physics=await readFile(new URL('../src/vehicle-physics.js',import.meta.url),'utf8');
const css=await readFile(new URL('../src/style.css',import.meta.url),'utf8');
const vite=await readFile(new URL('../vite.config.js',import.meta.url),'utf8');
const pkg=JSON.parse(await readFile(new URL('../package.json',import.meta.url),'utf8'));
assert.match(html,/id="application"/);
assert.match(html,/id="perf-toggle"/);
assert.match(html,/id="perf-panel"/);
assert.match(html,/id="traffic-status"/);
for(const control of ['accelerate','brake','left','right']) assert.match(html,new RegExp(`data-control="${control}"`));
assert.match(entry,/import\('\.\/game\.js'\)/,'Engine module must be lazy-loaded');
assert.doesNotMatch(entry,/from ['"]playcanvas['"]/,'Initial entry must not eagerly import PlayCanvas');
assert.match(game,/createGraphicsDevice/);
assert.match(game,/resourceHandlers = \[pc\.TextureHandler, pc\.ContainerHandler\]/,'GLB and texture handlers must be registered');
assert.match(game,/render-diagnostic-marker/,'A visible diagnostic object must be present');
assert.match(game,/__NAIJA_RENDER_DIAGNOSTICS__/,'Live render diagnostics must be exposed');
assert.match(assets,/instantiateRenderEntity/,'GLB containers must be instantiated into the scene');
assert.match(assets,/asset\.on\('progress'/,'Asset download progress must be reported');
assert.match(assets,/asset\.once\('error'/,'Asset failures must be reported explicitly');
assert.match(game,/RenderComponentSystem/);
assert.match(game,/CameraComponentSystem/);
assert.match(game,/app\.on\('update'/);
assert.match(game,/app\.on\('frameend'/);
assert.match(game,/stats\.frameTime/);
assert.match(game,/stats\.drawCallCount/);
assert.match(game,/stats\.vramTotalBytes/);
assert.match(game,/setCanvasFillMode\(pc\.FILLMODE_NONE\)/,'Canvas must use CSS-controlled mobile viewport sizing');
for(const feature of ['cross-street','north-crosswalk','bus-stop-sign','junction-bollard','pointerdown','keydown','traffic-main-','traffic-cross-','signal-red','updateSignal','trafficAI:true','createVehiclePhysics','physics.step','stage:4','wheelCount:4']) assert.ok(game.includes(feature),`Missing Stage 04 game feature: ${feature}`);
for(const feature of ['WasmModule.setConfig','btDiscreteDynamicsWorld','btRaycastVehicle','addWheel','set_m_suspensionStiffness','set_m_wheelsDampingCompression','applyEngineForce','setSteeringValue','setBrake','stepSimulation','CF_KINEMATIC_OBJECT']) assert.ok(physics.includes(feature),`Missing physics feature: ${feature}`);
assert.match(physics,/developer\.playcanvas\.com\/assets\/modules\/ammo/,'Ammo must load from the official PlayCanvas module host');
assert.match(physics,/1 \/ 60/,'Physics must use fixed 60 Hz substeps');
assert.match(css,/touch-action:\s*none/);
assert.match(vite,/chunkSizeWarningLimit:\s*1200/);
assert.ok(pkg.dependencies?.playcanvas);
assert.ok(pkg.devDependencies?.vite);
console.log('Stage 05 checks passed: WebGL viewport sizing, registered GLB/texture handlers, visible render marker, live camera/scene/draw-call diagnostics, asset progress and failure reporting, Ammo vehicle and mobile controls.');
